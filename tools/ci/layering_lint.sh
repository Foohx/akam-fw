#!/usr/bin/env bash
# Layering lint (local_check.sh, group lint; tests/layering_lint_test.sh proves that it catches violations).
#   (a) every C file of src/ compiles (-fsyntax-only, host compiler) with ONLY the shared include list (common_inc of src/build/sources.mk, plus
#       the third-party SmolRTSP headers): a shared file that includes a header of a platform or of a firmware directory cannot hide behind the -I
#       list of a build or of a test.
#   (b) in each build (platform + model), header basenames are unique across its whole include path, and C basenames are unique across the platform
#       directory and the model directory (headers are included by basename, so a duplicate is silently shadowed by the first -I match).
#   (c) the same C-basename rule is also enforced by the platform Makefiles themselves (an `own_%.o` rule that would pick the platform file and
#       ignore the model's), so a violation fails the build, not only this lint. Checked here by looking for that guard.
# Every firmware/*/model.mk must appear in BUILDS below, so a new model cannot skip the check.
#   LINT_SRC_DIR=<dir>   (tests only) lint another copy of src/
#   CC=<compiler>        host compiler for (a), default cc
set -uo pipefail
REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)
SRC=${LINT_SRC_DIR:-$REPO/src}
CCBIN=${CC:-cc}
BUILDS=("platforms/anyka-ak3918:lsc-indoor-1080p-ak3918" "platforms/anyka-ak3918av130:lsc-rotatable-2k-ak3918av130")
# LINT_BUILDS="platform:model ..." (tests only): check these builds instead (model = path relative to firmware/)
if [ -n "${LINT_BUILDS:-}" ]; then read -r -a BUILDS <<<"$LINT_BUILDS"; fi
fail=0
bad() { echo "layering_lint: FAIL: $*" >&2; fail=$((fail + 1)); }

# ---- every model is covered
for mk in "$REPO"/firmware/*/model.mk; do
    [ -z "${LINT_BUILDS:-}" ] || break
    id=$(basename "$(dirname "$mk")")
    found=0
    for b in "${BUILDS[@]}"; do [ "${b#*:}" = "$id" ] && found=1; done
    [ "$found" = 1 ] || bad "firmware/$id has a model.mk but is not listed in BUILDS of tools/ci/layering_lint.sh"
done

# ---- (a) src/ compiles with the shared include list only
# shellcheck disable=SC2016 # the $(...) is for make
shared_inc=$(printf 'SRC_DIR := %s\ninclude %s/build/sources.mk\nall:\n\t@echo $(common_inc)\n' "$SRC" "$REPO/src" | make -s -f -) ||
    { bad "cannot read common_inc from src/build/sources.mk"; shared_inc=""; }
# Directories of SRC that hold headers must be the ones the build list names (a new src/ directory needs an entry in SRC_SUBDIRS).
SM=$REPO/third_party/smolrtsp
smol_inc=()
if [ -d "$SM/build/_deps" ]; then
    smol_inc=(-I"$SM/include" -I"$SM/build/_deps/slice99-src" -I"$SM/build/_deps/datatype99-src" -I"$SM/build/_deps/interface99-src" -I"$SM/build/_deps/metalang99-src/include")
fi
# version_info.h is generated by the build (src/core/version/gen_version.sh) into the build directory: stand in for it.
STUB=$(mktemp -d)
trap 'rm -rf "$STUB"' EXIT
printf '#define BUILD_NUMBER 0\n#define BUILD_TIMESTAMP "lint"\n#define GIT_HASH "lint"\n' >"$STUB/version_info.h"
n=0
skipped=0
# shellcheck disable=SC2086 # shared_inc is a word list of -I options by design
while IFS= read -r f; do
    if grep -qE '^[[:space:]]*#[[:space:]]*include[[:space:]]*[<"]smolrtsp' "$f" && [ "${#smol_inc[@]}" -eq 0 ]; then skipped=$((skipped + 1)); continue; fi
    n=$((n + 1))
    out=$("$CCBIN" -fsyntax-only -w -std=gnu99 -D_GNU_SOURCE $shared_inc -I"$STUB" "${smol_inc[@]}" "$f" 2>&1) ||
        bad "(a) ${f#"$REPO"/} does not compile with the shared include list only: $(echo "$out" | grep -m1 -E 'error|fatal' | cut -c1-200)"
done < <(find "$SRC" -name '*.c' | LC_ALL=C sort)
echo "layering_lint: (a) $n src/ C files compile with the shared include list only ($skipped skipped for want of the SmolRTSP checkout)"

# ---- (b) unique basenames per build
for b in "${BUILDS[@]}"; do
    plat=${b%%:*}
    model=${b#*:}
    dirs=$(make -s -C "$REPO/$plat" MODEL="$model" print-incdirs 2>&1) || { bad "(b) make print-incdirs failed for $b: $dirs"; continue; }
    dup=$(for d in $dirs; do ls "$d"/*.h 2>/dev/null; done | awk -F/ '{print $NF}' | LC_ALL=C sort | uniq -d)
    [ -z "$dup" ] || bad "(b) $b: header basename present twice on the include path: $(echo "$dup" | tr "\n" " ")"
    # shellcheck disable=SC2012
    dupc=$(ls "$REPO/$plat"/*.c "$REPO/firmware/$model"/*.c 2>/dev/null | awk -F/ '{print $NF}' | LC_ALL=C sort | uniq -d)
    [ -z "$dupc" ] || bad "(b) $b: C basename in both the platform and the model directory: $(echo "$dupc" | tr "\n" " ")"
    echo "layering_lint: (b) $b: $(echo "$dirs" | wc -l) include directories, basenames unique"
done

# ---- (c) the Makefiles refuse a platform/model basename clash themselves
for b in "${BUILDS[@]}"; do
    grep -q 'basename clash' "$REPO/${b%%:*}/Makefile" || bad "(c) ${b%%:*}/Makefile has no 'basename clash' guard"
done
[ "$fail" -eq 0 ] && echo "layering_lint: OK"
exit $((fail > 0))
